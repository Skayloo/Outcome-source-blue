#!/usr/bin/env python3
"""Вырезает обещания шифрования из пользовательского руководства в экспортированном BLUE-дереве.

Вызывается из export-blue.sh. Крипто-доки экспорт удаляет целиком; руководство — нет, потому что
всё остальное в нём одинаково верно для обеих редакций. Неверно в blue ровно одно: сквозное
шифрование, а руководство, обещающее его тому, кто поднял дерево без него, хуже, чем отсутствие
руководства.

Контракт тот же, что у остальных strip-скриптов: точные куски, каждый обязан совпасть ровно один
раз. Поправите руководство — этот скрипт упадёт с тем куском, который перестал совпадать; чинить
надо здесь, а не в обход.
"""
import pathlib
import sys

dest = pathlib.Path(sys.argv[1])
guide = dest / "docs/user-guide.md"
if not guide.exists():
    sys.exit("!! docs/user-guide.md отсутствует в экспорте")

HUNKS: list[tuple[str, str]] = [
    # ── Вход: пароль здесь пароль, а не ключ ─────────────────────────────────
    (
        """**Отдельно про вход через провайдера.** Личные переписки зашифрованы сквозным шифрованием, а
ключ к ним завёрнут в ваш пароль. У аккаунта, созданного через провайдера, пароля может ещё не
быть — Outcome попросит его придумать и объяснит почему: это ещё и ключ. В новом браузере пароль
спросят ещё раз, чтобы расшифровать уже накопленную историю:

> **Разблокируйте переписку** — Вы вошли через провайдера на устройстве, которое никогда не
> держало ваш ключ. Личные сообщения зашифрованы вашим паролем — введите его один раз, и это
> устройство сможет их прочитать.

Кнопка **Позже** ничего не ломает: приложением можно пользоваться дальше, просто история личных
переписок на этом устройстве останется нечитаемой, пока её не разблокируешь.
""",
        """**Отдельно про вход через провайдера.** У аккаунта, созданного через провайдера, своего пароля
нет, а приложение для iOS умеет входить только по почте с паролем. Outcome попросит придумать
пароль при первом входе в вебе — чтобы тот же аккаунт работал и на телефоне.
""",
    ),
    # ── Личные чаты: что на самом деле лежит на сервере ───────────────────────
    (
        """**Личные сообщения зашифрованы сквозным шифрованием.** Сервер хранит шифротекст и прочитать его
не может — администратор тоже. Что это значит на практике:

- Новое устройство один раз спросит пароль, чтобы развернуть резервную копию ключа и
  расшифровать историю.
- Смена пароля перезаворачивает копию, так что история следует за аккаунтом.
- Если потерять и пароль, и резервную фразу, эта история пропала. Восстановить её не может
  никто — в этом и смысл слова «сквозное».
""",
        """**Личные сообщения приватные, но не тайные.** Они лежат на том сервере, куда вы вошли, и тот, кто
им управляет, может прочитать базу, в которой они хранятся. Входите туда, кому доверяете.
""",
    ),
    # ── iOS: строки про ключ и разблокировку в этой сборке просто нет ─────────
    (
        """В настройках лежат профиль, тема, пароль, чёрный список и фон для личных чатов — и одна строка,
которую стоит прочитать: она прямо говорит, шифрует ли **этот** сервер ваши личные переписки
сквозным шифрованием, и что это значит, если нет. Под ней, когда ключа на этом устройстве нет,
живёт **Разблокировать переписку** — телефонная половина той же резервной копии ключа, что и в
вебе. Пока не пройдёте через неё, зашифрованные диалоги показывают вместо последней строки
значок 🔒 — именно это и видно на скриншотах выше.
""",
        """В настройках лежат профиль, тема, пароль, чёрный список и фон для личных чатов.
""",
    ),
]

s = guide.read_text()
for old, new in HUNKS:
    n = s.count(old)
    if n != 1:
        sys.exit(f"!! docs/user-guide.md: ожидалось 1 совпадение, найдено {n} для:\n{old[:160]}")
    s = s.replace(old, new)
guide.write_text(s)
print(f"   user-guide.md: переписано кусков — {len(HUNKS)}")
